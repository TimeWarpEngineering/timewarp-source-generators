#region Purpose
// TWA0038 cases: the 500-line threshold, generated and path exemptions, the editorconfig override.
#endregion

#region Design
// SourceOfLines builds an exact wc -l count so 500 is clean and 501 warns. The first token is
// namespace on line 4, columns 1-10, unless a header prepends trivia.
#endregion

namespace TimeWarp.SourceGenerators.AnalyzerTests;

internal static class FileLengthAnalyzerTests
{
  public static readonly (string Name, Func<Task> Body)[] Cases =
  [
    ("trailing line break is not counted", TrailingLineBreak_Should_NotCount),
    ("file at the limit is clean", FileAtLimit_Should_BeClean),
    ("file over the limit warns", FileOverLimit_Should_ReportTwa0038),
    ("over-limit message names file and count", OverLimitMessage_Should_NameFileAndCount),
    ("auto-generated header is clean", AutoGeneratedHeader_Should_BeClean),
    ("generated file names are clean", GeneratedFileNames_Should_BeClean),
    ("generated_code editorconfig is clean", GeneratedCodeEditorConfig_Should_BeClean),
    ("obj or goldens path is clean", ObjOrGoldensPath_Should_BeClean),
    ("max_lines overrides the default", EditorConfigMaxLines_Should_OverrideDefault),
    ("pragma disable suppresses", PragmaDisable_Should_Suppress)
  ];

  public static Task TrailingLineBreak_Should_NotCount()
  {
    Expect.Equal(2, FileLengthAnalyzer.CountLines(SourceText.From("a\nb\n")), "Trailing break is not a line.");
    Expect.Equal(2, FileLengthAnalyzer.CountLines(SourceText.From("a\nb")), "A last line without a break still counts.");
    Expect.Equal(0, FileLengthAnalyzer.CountLines(SourceText.From(string.Empty)), "Empty text has no lines.");
    return Task.CompletedTask;
  }

  public static async Task FileAtLimit_Should_BeClean()
  {
    string source = SourceOfLines(FileLengthAnalyzer.DefaultMaximumLines);
    Expect.Equal(500, FileLengthAnalyzer.CountLines(SourceText.From(source)), "The fixture is 500 lines.");

    ImmutableArray<Diagnostic> diagnostics = await AnalyzeAsync("/src/widget.cs", source);
    Expect.Equal(0, diagnostics.Length, "Exactly 500 lines is clean.");
  }

  public static async Task FileOverLimit_Should_ReportTwa0038()
  {
    ImmutableArray<Diagnostic> diagnostics = await AnalyzeAsync("/src/widget.cs", SourceOfLines(501));
    Expect.Equal(1, diagnostics.Length, "501 lines warns.");
    Expect.Equal(FileLengthAnalyzer.DiagnosticId, diagnostics[0].Id, "Id stays TWA0038.");
    Expect.Contains("widget.cs", diagnostics[0].GetMessage(), "Message names the file.");
    Expect.Contains("501", diagnostics[0].GetMessage(), "Message names the count.");
    Expect.Contains("500", diagnostics[0].GetMessage(), "Message names the limit.");
    Expect.Span(diagnostics[0], 4, 1, 10, "Diagnostic anchors on the namespace token.");
  }

  public static async Task OverLimitMessage_Should_NameFileAndCount()
  {
    ImmutableArray<Diagnostic> diagnostics = await AnalyzeAsync("/src/widget.cs", SourceOfLines(612));
    Expect.Equal(1, diagnostics.Length, "612 lines warns once.");
    Expect.Equal(
      "File 'widget.cs' has 612 lines, over the 500-line limit; extract a responsibility into its own type",
      diagnostics[0].GetMessage(CultureInfo.InvariantCulture),
      "Message text stays stable for editorconfig consumers."
    );
  }

  public static async Task AutoGeneratedHeader_Should_BeClean()
  {
    ImmutableArray<Diagnostic> diagnostics = await AnalyzeAsync(
      "/src/widget.cs",
      SourceOfLines(800, "// <auto-generated/>\n")
    );
    Expect.Equal(0, diagnostics.Length, "An auto-generated header skips the tree.");
  }

  public static async Task GeneratedFileNames_Should_BeClean()
  {
    ImmutableArray<Diagnostic> generated = await AnalyzeAsync("/src/widget.g.cs", SourceOfLines(800));
    Expect.Equal(0, generated.Length, "*.g.cs is generated.");

    ImmutableArray<Diagnostic> designer = await AnalyzeAsync("/src/Widget.Designer.cs", SourceOfLines(800));
    Expect.Equal(0, designer.Length, "*.Designer.cs is generated.");
  }

  public static async Task GeneratedCodeEditorConfig_Should_BeClean()
  {
    ImmutableArray<Diagnostic> diagnostics = await AnalyzeAsync(
      "/src/platform/postgres/migrations/20261102105501_AddAgentScopeGrants.cs",
      SourceOfLines(800),
      new Dictionary<string, string> { ["generated_code"] = "true" }
    );
    Expect.Equal(0, diagnostics.Length, "editorconfig generated_code skips the tree.");
  }

  public static async Task ObjOrGoldensPath_Should_BeClean()
  {
    ImmutableArray<Diagnostic> obj = await AnalyzeAsync("/src/obj/debug/widget.cs", SourceOfLines(800));
    Expect.Equal(0, obj.Length, "An obj/ segment is exempt.");

    ImmutableArray<Diagnostic> goldens = await AnalyzeAsync("/repo/goldens/ingress/widget.cs", SourceOfLines(800));
    Expect.Equal(0, goldens.Length, "A goldens/ segment is exempt.");
  }

  public static async Task EditorConfigMaxLines_Should_OverrideDefault()
  {
    Dictionary<string, string> config = new()
    {
      [FileLengthAnalyzer.MaximumLinesOptionKey] = "600"
    };

    ImmutableArray<Diagnostic> atLimit = await AnalyzeAsync("/src/widget.cs", SourceOfLines(600), config);
    Expect.Equal(0, atLimit.Length, "600 lines is the configured limit.");

    ImmutableArray<Diagnostic> over = await AnalyzeAsync("/src/widget.cs", SourceOfLines(601), config);
    Expect.Equal(1, over.Length, "601 lines exceeds the configured limit.");
    Expect.Contains("601", over[0].GetMessage(), "Message names the count.");
    Expect.Contains("600", over[0].GetMessage(), "Message names the configured limit.");
    Expect.Span(over[0], 4, 1, 10, "Diagnostic still anchors on the namespace token.");
  }

  public static async Task PragmaDisable_Should_Suppress()
  {
    ImmutableArray<Diagnostic> diagnostics = await AnalyzeAsync(
      "/src/widget.cs",
      SourceOfLines(800, "#pragma warning disable TWA0038\n")
    );
    Expect.Equal(0, diagnostics.Length, "A leading pragma disable suppresses TWA0038.");
  }

  private static string SourceOfLines(int lineCount, string header = "")
  {
    StringBuilder builder = new();
    builder.Append("#region Purpose\n// Widget used to exercise the file-length limit.\n#endregion\n");
    builder.Append("namespace Contracts;\npublic class Widget\n{\n");
    const int FixedLines = 3 + 3 + 1;
    for (int line = 0; line < lineCount - FixedLines; line++)
    {
      builder.Append("  // filler\n");
    }

    builder.Append("}\n");
    return header + builder;
  }

  private static Task<ImmutableArray<Diagnostic>> AnalyzeAsync(
    string path,
    string source,
    Dictionary<string, string>? analyzerConfig = null) =>
    AnalyzerTestDriver.AnalyzeAsync(new FileLengthAnalyzer(), source, path, analyzerConfig);
}
